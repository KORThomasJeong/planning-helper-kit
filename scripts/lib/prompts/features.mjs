/** 생성·수정 모드 사용자 프롬프트. */
export function userPrompt({ prd, task_definition, requirements, revision_request, current_content }) {
    const userContent = revision_request
        ? `아래 기능 정리를 수정 요청 사항에 맞게 수정해주세요.\n\n수정 요청:\n${revision_request}\n\n현재 기능 정리:\n${current_content}\n\n원본 PRD:\n${prd}`
        : `PRD:\n${prd}\n\n과제 정의서:\n${task_definition || "(없음)"}\n\n요구사항:\n${requirements || "(없음)"}`;
    return userContent;
}
