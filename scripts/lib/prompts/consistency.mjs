const ORDER = ["task_definition", "requirements", "prd", "feature_spec", "foundation", "design_spec", "dev_spec"];
/** 문서 본문이 구획 태그를 닫지 못하게 한다 (`</document` → `<\/document`). */
function fence(content) {
    if (!content || !content.trim())
        return "(아직 없음)";
    return content.replace(/<\/(document)/gi, "<\\/$1");
}
export function userPrompt(input) {
    const docs = ORDER.map((name) => `<document name="${name}">\n${fence(input[name])}\n</document>`).join("\n\n");
    return `아래 기획 문서들의 일관성을 점검해주세요.\n\n${docs}`;
}
